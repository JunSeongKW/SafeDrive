"""Official LPWM encoder/context/dynamics jointly connected to trajectory planning.

The original RGB decoder is omitted. Future particles are obtained by the
official autoregressive prior rollout, without teacher-forced future inputs.
"""
import contextlib
import io

import torch
from torch import nn
from torch.utils.checkpoint import checkpoint

from .lpwm_bridge import load_official_lpwm
from .lpwm_planner import IntentConditionedParticlePlanner, normalized_ego_status, particle_image_boxes


def pack_particle_attributes(encoded, presence_key="obj_on"):
    return torch.cat((encoded["z"], encoded["z_scale"].sigmoid(), encoded[presence_key],
                      encoded["z_depth"].tanh(), encoded["z_features"].tanh(),
                      encoded["z_bg_features"][:, :, None].expand(-1, -1, 64, -1).tanh()), -1)


class JointLPWMWorldPlanner(IntentConditionedParticlePlanner):
    def __init__(self, checkpoint_path, condition="joint_future", future_steps=8, checkpoint_rollout=True):
        super().__init__(checkpoint_path, "planning_joint")
        with contextlib.redirect_stdout(io.StringIO()):
            official_model, _ = load_official_lpwm("cpu", checkpoint_path)
        self.particle_encoder = official_model.encoder_module
        self.particle_dynamics = official_model.dyn_module
        assert self.particle_encoder.ctx_enc is self.particle_dynamics.context_decoder
        self.particle_encoder.particle_enc.particle_attribute_enc.cnn.conv_in.register_forward_hook(self._condition_attribute_features)
        self.condition = condition
        self.encoder_frozen = condition == "frozen_world"
        self.encoder_intent_enabled = not self.encoder_frozen
        self.future_steps = future_steps
        self.checkpoint_rollout = checkpoint_rollout
        self.future_time_embedding = nn.Parameter(torch.randn(future_steps, 128) * .02)
        self.future_object_attention = nn.MultiheadAttention(128, 4, dropout=0., batch_first=True)
        self.future_object_state_head = nn.Sequential(nn.Linear(128, 128), nn.GELU(), nn.Linear(128, 2))
        # The current state head is reused; the old direct 8-step future readout is not used.
        self.future_state_projection = nn.Identity()
        if self.encoder_frozen:
            self.particle_encoder.requires_grad_(False)
            self.particle_dynamics.requires_grad_(False)
            self.encoder_intent_film.requires_grad_(False)
        del official_model

    def world_parameter_groups(self):
        context_ids = {id(parameter) for parameter in self.particle_encoder.ctx_enc.parameters()}
        encoder_ids = {id(parameter) for parameter in self.particle_encoder.parameters()} - context_ids
        dynamics_ids = {id(parameter) for parameter in self.particle_dynamics.parameters()} - context_ids
        groups = {"image_encoder": [], "context": [], "dynamics": [], "planner_and_intent": []}
        for parameter in self.parameters():
            identity = id(parameter)
            group = "context" if identity in context_ids else "image_encoder" if identity in encoder_ids else "dynamics" if identity in dynamics_ids else "planner_and_intent"
            groups[group].append(parameter)
        return groups

    def _rollout(self, observed_positions, observed_scales, observed_presence, observed_depth,
                 observed_features, observed_background, observed_context, observed_scores):
        return self.particle_dynamics.sample(observed_positions, observed_scales, observed_presence,
                                            observed_depth, observed_features, observed_background,
                                            z_context=observed_context, z_score=observed_scores,
                                            steps=self.future_steps, deterministic=True, return_context_posterior=False)

    def encode_and_rollout(self, observed_images, ego_status):
        assert observed_images.ndim == 5 and observed_images.shape[1:] == (2, 3, 128, 128)
        self._active_ego_status = ego_status
        try:
            encoder_input = observed_images * 2 - 1 if self.normalize_rgb else observed_images
            # The released image encoder scatters CNN outputs into FP32 buffers.
            # Preserve its FP32 arithmetic; dynamics/planner may use autocast.
            with torch.autocast(observed_images.device.type, enabled=False):
                encoded = self.particle_encoder(encoder_input.float(), deterministic=True)
        finally:
            self._active_ego_status = None
        # Only the observed transition t-0.5 -> t uses the inverse-dynamics posterior.
        # Every unobserved transition is generated by the official latent-policy prior.
        arguments = (encoded["z"], encoded["z_scale"], encoded["obj_on"], encoded["z_depth"],
                     encoded["z_features"], encoded["z_bg_features"], encoded["z_context"][:, 1:].contiguous(), encoded["z_score"])
        if self.training and not self.encoder_frozen and self.checkpoint_rollout:
            rolled = checkpoint(self._rollout, *arguments, use_reentrant=False)
        else:
            rolled = self._rollout(*arguments)
        return encoded, rolled

    def forward(self, observed_images, ego_status, intervention=None):
        if self.encoder_frozen:
            self.particle_encoder.eval()
            self.particle_dynamics.eval()
            with torch.no_grad():
                encoded, rolled = self.encode_and_rollout(observed_images, ego_status)
        else:
            encoded, rolled = self.encode_and_rollout(observed_images, ego_status)
        observed_attributes = pack_particle_attributes(encoded)
        future_attributes = pack_particle_attributes(rolled, "z_obj_on")[:, -self.future_steps:]
        if intervention == "future_particle_persistence":
            future_attributes = observed_attributes[:, -1:].expand(-1, self.future_steps, -1, -1)
        elif intervention == "shuffle_predicted_futures":
            future_attributes = future_attributes.roll(1, 0)
        observed_particles = self.particle_projection(observed_attributes)
        observed_particles = observed_particles + self.observation_time_embedding[None, :, None] + self.particle_index_embedding[None, None]
        observed_memory = self.observed_particle_attention(observed_particles.flatten(1, 2))
        current_memory = observed_memory[:, -64:]
        future_memory = self.particle_projection(future_attributes) + self.future_time_embedding[None, :, None] + self.particle_index_embedding[None, None]
        future_queries = current_memory[:, None] + self.future_time_embedding[None, :, None]
        future_object_features, _ = self.future_object_attention(future_queries.flatten(0, 1), future_memory.flatten(0, 1), future_memory.flatten(0, 1), need_weights=False)
        future_object_features = future_object_features.reshape(len(ego_status), self.future_steps, 64, 128)
        current_xy = self.object_state_head(current_memory)[..., :2] * 20
        future_xy = self.future_object_state_head(future_object_features).permute(0, 2, 1, 3) * 20
        planner_memory = torch.cat((observed_memory, future_memory.flatten(1, 2)), 1)
        queries = self.trajectory_queries[None] + self.ego_projection(normalized_ego_status(ego_status))[:, None]
        decoded = self.trajectory_decoder(queries, planner_memory)
        future_times = torch.arange(1, 9, device=ego_status.device, dtype=ego_status.dtype) * .5
        kinematic = ego_status.new_zeros((len(ego_status), 8, 3))
        kinematic[..., :2] = ego_status[:, None, 4:6] * future_times[None, :, None]
        trajectory = kinematic + self.trajectory_head(decoded) * decoded.new_tensor([10, 10, 1])
        return {"trajectory": trajectory, "particle_attributes": observed_attributes, "predicted_future_attributes": future_attributes,
                "current_boxes": particle_image_boxes(encoded["z"][:, -1], encoded["z_scale"][:, -1]),
                "current_xy": current_xy, "future_xy": future_xy,
                "object_class_logits": self.object_class_head(current_memory)}
